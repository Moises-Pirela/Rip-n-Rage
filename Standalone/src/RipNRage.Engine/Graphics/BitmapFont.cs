        public static BitmapFont CreateBuiltin()
        {
            var font = new BitmapFont();
            int count = Glyphs.Count;
            int cols = 16;
            int rows = (count + cols - 1) / cols;
            var img = new Image(cols * Cell, rows * Cell);
            int i = 0;
            foreach (var kv in Glyphs)
            {
                int cx = (i % cols) * Cell, cy = (i / cols) * Cell;
                for (int y = 0; y < GlyphH; y++)
                    for (int x = 0; x < GlyphW; x++)
                    {
                        if (kv.Value[y][x] != '#') continue;
                        int o = ((cy + y) * img.Width + cx + x) * 4;
                        img.Pixels[o] = img.Pixels[o + 1] = img.Pixels[o + 2] = img.Pixels[o + 3] = 255;
                    }
                // rect with bottom-left origin for the Sprite convention
                font._glyphs[kv.Key] = new Rect(cx, img.Height - cy - GlyphH, GlyphW, GlyphH);
                i++;
            }
            font._texture = Texture2D.Create(img, FilterMode.Point, TextureWrapMode.Clamp, false, "BuiltinFont");
            return font;
        }

        public Vector2 Measure(string text, float scale)
        {
            float w = 0, maxW = 0; int lines = 1;
            foreach (char c in text)
            {
                if (c == '\n') { lines++; maxW = Mathf.Max(maxW, w); w = 0; continue; }
                w += (GlyphW + 1) * scale;
            }
            return new Vector2(Mathf.Max(maxW, w), lines * (GlyphH + 1) * scale);
        }

        /// <summary>Draws text with its top-left corner at <paramref name="pos"/> (pixels, origin bottom-left).</summary>
        public void Draw(UiBatch batch, string text, Vector2 pos, float scale, Color color)
        {
            float x = pos.x, y = pos.y - GlyphH * scale;
            foreach (char raw in text)
            {
                char c = char.ToUpperInvariant(raw);
                if (c == '\n') { x = pos.x; y -= (GlyphH + 1) * scale; continue; }
                if (_glyphs.TryGetValue(c, out var r))
                {
                    float u0 = r.x / _texture.width, v0 = r.y / _texture.height;
                    float u1 = (r.x + r.width) / _texture.width, v1 = (r.y + r.height) / _texture.height;
                    batch.DrawRaw(_texture, new Rect(x, y, GlyphW * scale, GlyphH * scale), u0, v0, u1, v1, color);
                }
                x += (GlyphW + 1) * scale;
            }
        }
